import org.jetbrains.compose.desktop.application.dsl.TargetFormat

// Flux for Windows (PC version). Included only with -Pdesktop (settings.gradle.kts), never by the
// Android gate. Android is the main version; this module follows it on request (see SYNC.md).
plugins {
    alias(libs.plugins.kotlin.jvm)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.kotlin.serialization)
    alias(libs.plugins.compose.multiplatform)
}

/** Desktop version (x.y.z, MSI needs a numeric version with major > 0, see packageVersion below). */
val fluxVersion = "0.1.4-test3"

kotlin { jvmToolchain(17) }

dependencies {
    implementation(project(":core:model"))
    implementation(project(":core:parser"))
    implementation(project(":core:update"))
    implementation(compose.desktop.currentOs)
    implementation(compose.material3)
    implementation(compose.materialIconsExtended)
    implementation(libs.kotlinx.coroutines.swing)
    implementation(libs.kotlinx.serialization.json)
    implementation(libs.xmlpull)
    implementation(libs.kxml2)
    implementation(libs.pdfbox)

    testImplementation(libs.junit.jupiter)
    testRuntimeOnly(libs.junit.platform.launcher)
    testImplementation(compose.desktop.uiTestJUnit4)
}

val generateVersion by tasks.registering {
    val out = layout.buildDirectory.dir("generated/version")
    val version = fluxVersion
    val syncFile = file("SYNC.md")
    inputs.property("version", version)
    inputs.file(syncFile).optional()
    outputs.dir(out)
    doLast {
        val synced = syncFile.takeIf { it.exists() }?.readLines()?.firstOrNull { it.startsWith("Synced with Android:") }
            ?.removePrefix("Synced with Android:")?.trim() ?: "unknown"
        val dir = out.get().asFile.resolve("com/pcbsolderview/platform").apply { mkdirs() }
        dir.resolve("BuildInfo.kt").writeText(
            """
            |package com.pcbsolderview.platform
            |
            |/** Generated by desktop/build.gradle.kts. */
            |object BuildInfo {
            |    const val VERSION = "$version"
            |    const val SYNCED_WITH = "${synced.replace("\"", "'")}"
            |}
            |""".trimMargin()
        )
    }
}
kotlin.sourceSets["main"].kotlin.srcDir(generateVersion)

tasks.test {
    useJUnitPlatform()
    systemProperty("samples.dir", rootProject.file("samples").absolutePath)
    systemProperty("renders.dir", layout.buildDirectory.dir("renders").get().asFile.absolutePath)
    inputs.files(rootProject.fileTree("samples/synthetic")).withPropertyName("samples")
    // Off-screen Compose renders need a headless AWT.
    systemProperty("java.awt.headless", "true")
}

// The demos (samples/synthetic) are packaged as resources under demos/, as Android ships them as
// assets, with an index (demos/index.txt: "folder/file" per line) because jars cannot be listed.
val packageDemos by tasks.registering {
    val src = rootProject.file("samples/synthetic")
    val out = layout.buildDirectory.dir("generated/demos")
    inputs.dir(src)
    outputs.dir(out)
    doLast {
        val root = out.get().asFile.resolve("demos")
        root.deleteRecursively()
        val names = src.walkTopDown().filter { it.isFile }.map { it.relativeTo(src).invariantSeparatorsPath }.sorted().toList()
        names.forEach { n -> src.resolve(n).copyTo(root.resolve(n), overwrite = true) }
        root.resolve("index.txt").writeText(names.joinToString("\n"))
    }
}
sourceSets["main"].resources.srcDir(packageDemos)

compose.desktop {
    application {
        mainClass = "com.pcbsolderview.MainKt"
        jvmArgs += listOf("-Xmx2g", "-Dsun.java2d.uiScale.enabled=true")
        // Dev runs: -PfluxArgs="file1|file2" opens files, -PfluxHome=<dir> uses another data folder.
        (project.findProperty("fluxArgs") as String?)?.let { a -> args += a.split("|") }
        (project.findProperty("fluxHome") as String?)?.let { h -> jvmArgs += "-Dflux.home=$h" }
        nativeDistributions {
            targetFormats(TargetFormat.Msi, TargetFormat.Exe)
            packageName = "Flux"
            packageVersion = fluxVersion.substringBefore("-") // MSI needs numbers only: 0.1.4-test1 -> 0.1.4
            description = "PCB viewer for the soldering bench"
            vendor = "Vinicius Alexandre Gomes"
            // java.naming etc. are not needed; PDFBox needs java.desktop (always included).
            modules("java.naming", "jdk.unsupported")
            windows {
                menuGroup = "Flux"
                // Never change: Windows uses it to upgrade an installed Flux in place.
                upgradeUuid = "6f1c2f0e-3d1b-4c55-9a43-1f0b8b7a2c61"
                shortcut = true
                dirChooser = true
                perUserInstall = true
                iconFile.set(project.file("icons/flux.ico"))
            }
        }
    }
}
